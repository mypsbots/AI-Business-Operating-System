import re

_DOC_SUFFIXES = (" rule", " checklist", " playbook", " template",
                 " knowledge article", " knowledge", " framework")


def topic_key(title: str) -> str:
    """Normalise an artefact title to a canonical topic key."""
    t = title.lower().strip()
    for suffix in _DOC_SUFFIXES:
        if t.endswith(suffix):
            t = t[: -len(suffix)].strip()
            break
    if t in ALIASES:
        return ALIASES[t]
    return re.sub(r"[^a-z0-9]+", "_", t).strip("_")


