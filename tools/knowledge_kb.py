def get(domain: str, title: str) -> dict:
    """Return a normalised content dict for a knowledge article."""
    if domain == "Industry_Playbooks" and title in INDUSTRIES:
        ind = INDUSTRIES[title]
        return {
            "industry": True,
            "summary": ind["summary"],
            "concepts": ind["opportunities"],
            "best": ["Start with a high-value, low-risk use case and a clear metric.",
                     "Ground AI in approved, current sources (RAG) and cite them.",
                     "Keep a human in the loop for regulated or high-impact decisions.",
                     "Map and meet the industry's compliance obligations early."],
            "anti": ["Deploying AI into regulated decisions without oversight.",
                     "Ignoring sector-specific compliance.",
                     "Boiling the ocean instead of proving one use case."],
            "faqs": [("Where should this industry start with AI?",
                      "With a narrow, high-value use case (often document or "
                      "service automation) that has measurable ROI and low "
                      "regulatory risk."),
                     ("What is the biggest risk?",
                      "Compliance and trust — regulated decisions need human "
                      "oversight, auditability and grounded, citable answers.")],
            "learning": ["Map the industry value chain and pain points.",
                         "Identify a high-ROI, low-risk AI use case.",
                         "Design controls for the relevant regulations."],
            "keywords": ind["keywords"],
            "usecases": ind["usecases"],
            "compliance": ind["compliance"],
            "challenges": ind["challenges"],
            "defs": [], "examples": ind["usecases"], "patterns": [],
            "standards": ["ISO 42001", "NIST AI RMF"],
        }
    e = KB.get(title)
    if e:
        e = dict(e)
        e["industry"] = False
        e.setdefault("usecases", [])
        e.setdefault("compliance", [])
        e.setdefault("challenges", [])
    return e
